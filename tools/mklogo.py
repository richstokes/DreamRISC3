#!/usr/bin/env python3
"""Generate assets/acorn-logo.svg and render assets/acorn-logo.png (320x90) for the
Dreamcast licence screen (mkdcdisc --bootstrap-mr-image). Background is #c0c0c0, the
licence screen grey. Needs rsvg-convert and ImageMagick to render."""
import math, subprocess, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
svg_path = root / "assets/acorn-logo.svg"
png_path = root / "assets/acorn-logo.png"

BG, GREEN, BLUE, INK, GREY, ORANGE = "#c0c0c0", "#4caf63", "#2f6fd1", "#1f1f1f", "#555555", "#b8632a"


def swirl(cx, cy, radius, r_min=3.5, turns=2.5, width=4.4, start_deg=0, steps=900):
    """Dreamcast-style spiral: an even, near-uniform stroke of about two and a half turns,
    open end on the right winding counter-clockwise inward, rounded ends, a slight taper
    at the open end. Returns (spiral path, [(x, y, r) end caps])."""
    import math
    total = turns * 2 * math.pi
    w = lambda t: width * (0.7 + 0.3 * min(1.0, t / 0.2))
    outer, inner = [], []
    for i in range(steps + 1):
        t = i / steps
        th = math.radians(start_deg) - t * total      # minus: counter-clockwise on screen
        r = radius - t * (radius - r_min)
        c, s = math.cos(th), math.sin(th)
        ww = w(t)
        outer.append((cx + (r + ww / 2) * c, cy + (r + ww / 2) * s))
        inner.append((cx + (r - ww / 2) * c, cy + (r - ww / 2) * s))
    pts = outer + inner[::-1]
    path = "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"
    caps = []
    for t in (0.0, 1.0):
        th = math.radians(start_deg) - t * total
        r = radius - t * (radius - r_min)
        caps.append((cx + r * math.cos(th), cy + r * math.sin(th), w(t) / 2))
    return path, caps


cap = "M24 35 C24 18, 38 10, 56 10 C74 10, 88 18, 88 35 Z"
stem = "M56 12 Q57 5 63 3"

spiral, caps = swirl(56, 58, 26.5)
cap_circles = "".join(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{r:.2f}" fill="{BLUE}"/>' for x, y, r in caps)

svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/mklogo.py; edit that, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" width="320" height="90" viewBox="0 0 320 90">
  <rect width="320" height="90" fill="{BG}"/>
  <!-- swirl (nut) -->
  <path d="{spiral}" fill="{BLUE}"/>
  {cap_circles}
  <!-- cap and stem -->
  <path d="{cap}" fill="{GREEN}" stroke="{GREEN}" stroke-width="4" stroke-linejoin="round"/>
  <path d="{stem}" fill="none" stroke="{GREEN}" stroke-width="5" stroke-linecap="round"/>
  <!-- wordmark -->
  <text x="112" y="52" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-weight="700"
        font-size="34" fill="{INK}" letter-spacing="-1">Dream<tspan fill="{BLUE}">RISC</tspan></text>
  <text x="114" y="73" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-weight="400"
        font-size="12" fill="{GREY}" letter-spacing="1">RISC OS 3.11 ON DREAMCAST</text>
</svg>
"""
svg_path.write_text(svg)
if "--no-render" not in sys.argv:
    subprocess.run(["rsvg-convert", "-w", "320", "-h", "90", svg_path, "-o", "/tmp/acorn-raw.png"], check=True)
    subprocess.run(["magick", "/tmp/acorn-raw.png", "-background", BG, "-alpha", "remove", "+dither",
                    "-colors", "32", "-type", "Palette", f"PNG8:{png_path}"], check=True)
    print(subprocess.run(["magick", png_path, "-format", "%wx%h %k colours", "info:"],
                         capture_output=True, text=True, check=True).stdout)
